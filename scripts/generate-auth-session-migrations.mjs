import { mkdir, writeFile } from "node:fs/promises";

function migration(schema) {
  return `-- Generated by scripts/generate-auth-session-migrations.mjs. Do not edit manually.
alter table ${schema}.wallet_login_challenges
  add column if not exists message_hash bytea;

create or replace function ${schema}.complete_wallet_login(
  p_challenge_id uuid,
  p_wallet_address text,
  p_nonce_hash_hex text,
  p_message_hash_hex text,
  p_session_token_hash_hex text,
  p_session_expires_at timestamptz
)
returns table (user_id uuid, wallet_id uuid)
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_wallet_id uuid;
  v_user_id uuid;
begin
  update ${schema}.wallet_login_challenges
  set consumed_at = now()
  where id = p_challenge_id
    and wallet_address = lower(p_wallet_address)
    and nonce_hash = decode(p_nonce_hash_hex, 'hex')
    and message_hash = decode(p_message_hash_hex, 'hex')
    and consumed_at is null
    and expires_at > now();

  if not found then
    raise exception 'INVALID_OR_EXPIRED_CHALLENGE' using errcode = 'P0001';
  end if;

  select uw.id, uw.user_id into v_wallet_id, v_user_id
  from ${schema}.user_wallets uw
  where uw.wallet_address = lower(p_wallet_address)
  for update;

  if v_wallet_id is null then
    insert into ${schema}.users (login_count, first_login_at, last_login_at)
    values (1, now(), now())
    returning id into v_user_id;

    insert into ${schema}.user_wallets (
      user_id, wallet_address, is_primary, verified_at
    ) values (
      v_user_id, lower(p_wallet_address), true, now()
    ) returning id into v_wallet_id;
  else
    update ${schema}.users
    set login_count = login_count + 1,
        first_login_at = coalesce(first_login_at, now()),
        last_login_at = now()
    where id = v_user_id and status = 'active';

    if not found then
      raise exception 'ACCOUNT_NOT_ACTIVE' using errcode = 'P0001';
    end if;
  end if;

  insert into ${schema}.user_sessions (
    user_id, wallet_id, token_hash, expires_at
  ) values (
    v_user_id,
    v_wallet_id,
    decode(p_session_token_hash_hex, 'hex'),
    p_session_expires_at
  );

  insert into ${schema}.login_attempts (wallet_address, success)
  values (lower(p_wallet_address), true);

  return query select v_user_id, v_wallet_id;
end;
$$;

revoke all on function ${schema}.complete_wallet_login(
  uuid, text, text, text, text, timestamptz
) from public, anon, authenticated;
grant execute on function ${schema}.complete_wallet_login(
  uuid, text, text, text, text, timestamptz
) to service_role;
`;
}

for (const environment of ["testnet", "mainnet"]) {
  const directory = `supabase/migrations/${environment}`;
  await mkdir(directory, { recursive: true });
  await writeFile(
    `${directory}/202610160002_atomic_wallet_login.sql`,
    migration(`zkblast_${environment}`),
  );
}

