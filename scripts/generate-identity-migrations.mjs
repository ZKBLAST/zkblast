import { mkdir, writeFile } from "node:fs/promises";

const environments = ["testnet", "mainnet"];

function migration(schema) {
  return `-- Generated by scripts/generate-identity-migrations.mjs. Do not edit manually.
create extension if not exists pgcrypto with schema extensions;

create schema if not exists ${schema};
revoke all on schema ${schema} from public, anon, authenticated;
grant usage on schema ${schema} to service_role;

create table ${schema}.users (
  id uuid primary key default extensions.gen_random_uuid(),
  username text,
  status text not null default 'active' check (status in ('active', 'suspended', 'deleted')),
  login_count bigint not null default 0 check (login_count >= 0),
  first_login_at timestamptz,
  last_login_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint users_username_format check (
    username is null or username ~ '^[a-zA-Z0-9_]{3,24}$'
  )
);
create unique index users_username_unique_ci
  on ${schema}.users (lower(username)) where username is not null;

create table ${schema}.user_wallets (
  id uuid primary key default extensions.gen_random_uuid(),
  user_id uuid not null references ${schema}.users(id) on delete cascade,
  wallet_address text not null,
  is_primary boolean not null default false,
  verified_at timestamptz not null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint user_wallets_address_format check (wallet_address ~ '^0x[0-9a-f]{40}$')
);
create unique index user_wallets_address_unique on ${schema}.user_wallets (wallet_address);
create unique index user_wallets_one_primary
  on ${schema}.user_wallets (user_id) where is_primary;
create index user_wallets_user_id_idx on ${schema}.user_wallets (user_id);

create table ${schema}.wallet_login_challenges (
  id uuid primary key default extensions.gen_random_uuid(),
  wallet_address text not null,
  nonce_hash bytea not null unique,
  domain text not null,
  uri text not null,
  chain_id bigint not null check (chain_id > 0),
  issued_at timestamptz not null default now(),
  expires_at timestamptz not null,
  consumed_at timestamptz,
  constraint wallet_login_challenges_address_format check (wallet_address ~ '^0x[0-9a-f]{40}$'),
  constraint wallet_login_challenges_expiry check (expires_at > issued_at)
);
create index wallet_login_challenges_lookup_idx
  on ${schema}.wallet_login_challenges (wallet_address, expires_at desc);

create table ${schema}.user_sessions (
  id uuid primary key default extensions.gen_random_uuid(),
  user_id uuid not null references ${schema}.users(id) on delete cascade,
  wallet_id uuid not null references ${schema}.user_wallets(id) on delete cascade,
  token_hash bytea not null unique,
  expires_at timestamptz not null,
  revoked_at timestamptz,
  created_at timestamptz not null default now(),
  last_seen_at timestamptz not null default now(),
  constraint user_sessions_expiry check (expires_at > created_at)
);
create index user_sessions_user_idx on ${schema}.user_sessions (user_id, expires_at desc);

create table ${schema}.login_attempts (
  id bigint generated always as identity primary key,
  wallet_address text,
  success boolean not null,
  failure_code text,
  network_fingerprint_hash bytea,
  user_agent_hash bytea,
  attempted_at timestamptz not null default now(),
  constraint login_attempts_address_format check (
    wallet_address is null or wallet_address ~ '^0x[0-9a-f]{40}$'
  ),
  constraint login_attempts_failure_consistency check (
    (success and failure_code is null) or (not success and failure_code is not null)
  )
);
create index login_attempts_wallet_time_idx
  on ${schema}.login_attempts (wallet_address, attempted_at desc);
create index login_attempts_time_idx on ${schema}.login_attempts (attempted_at desc);

create table ${schema}.trade_history (
  id uuid primary key default extensions.gen_random_uuid(),
  user_id uuid not null references ${schema}.users(id) on delete restrict,
  wallet_id uuid not null references ${schema}.user_wallets(id) on delete restrict,
  client_request_id uuid not null unique,
  chain_id bigint not null check (chain_id > 0),
  transaction_hash text,
  log_index integer,
  action text not null check (action in ('swap', 'add_liquidity', 'remove_liquidity', 'claim_fees')),
  status text not null check (status in ('submitted', 'confirmed', 'reverted', 'replaced', 'dropped')),
  venue text not null,
  pool_address text,
  token_in_address text,
  token_out_address text,
  amount_in_raw numeric(78, 0),
  amount_out_raw numeric(78, 0),
  fee_raw numeric(78, 0),
  block_number bigint,
  block_timestamp timestamptz,
  submitted_at timestamptz not null default now(),
  confirmed_at timestamptz,
  updated_at timestamptz not null default now(),
  error_code text,
  constraint trade_history_tx_hash_format check (
    transaction_hash is null or transaction_hash ~ '^0x[0-9a-f]{64}$'
  ),
  constraint trade_history_pool_format check (
    pool_address is null or pool_address ~ '^0x[0-9a-f]{40}$'
  ),
  constraint trade_history_token_in_format check (
    token_in_address is null or token_in_address ~ '^0x[0-9a-f]{40}$'
  ),
  constraint trade_history_token_out_format check (
    token_out_address is null or token_out_address ~ '^0x[0-9a-f]{40}$'
  ),
  constraint trade_history_log_index check (log_index is null or log_index >= 0),
  constraint trade_history_amount_in check (amount_in_raw is null or amount_in_raw >= 0),
  constraint trade_history_amount_out check (amount_out_raw is null or amount_out_raw >= 0),
  constraint trade_history_fee check (fee_raw is null or fee_raw >= 0)
);
create unique index trade_history_chain_log_unique
  on ${schema}.trade_history (chain_id, transaction_hash, log_index)
  where transaction_hash is not null and log_index is not null;
create index trade_history_user_time_idx
  on ${schema}.trade_history (user_id, submitted_at desc);
create index trade_history_wallet_time_idx
  on ${schema}.trade_history (wallet_id, submitted_at desc);
create index trade_history_status_idx
  on ${schema}.trade_history (status, updated_at desc);

create or replace function ${schema}.set_updated_at()
returns trigger language plpgsql security invoker set search_path = '' as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

create trigger users_set_updated_at before update on ${schema}.users
  for each row execute function ${schema}.set_updated_at();
create trigger user_wallets_set_updated_at before update on ${schema}.user_wallets
  for each row execute function ${schema}.set_updated_at();
create trigger trade_history_set_updated_at before update on ${schema}.trade_history
  for each row execute function ${schema}.set_updated_at();

alter table ${schema}.users enable row level security;
alter table ${schema}.user_wallets enable row level security;
alter table ${schema}.wallet_login_challenges enable row level security;
alter table ${schema}.user_sessions enable row level security;
alter table ${schema}.login_attempts enable row level security;
alter table ${schema}.trade_history enable row level security;

revoke all on all tables in schema ${schema} from public, anon, authenticated;
revoke all on all sequences in schema ${schema} from public, anon, authenticated;
grant select, insert, update, delete on all tables in schema ${schema} to service_role;
grant usage, select on all sequences in schema ${schema} to service_role;

alter default privileges in schema ${schema}
  revoke all on tables from public, anon, authenticated;
alter default privileges in schema ${schema}
  revoke all on sequences from public, anon, authenticated;
alter default privileges in schema ${schema}
  grant select, insert, update, delete on tables to service_role;
alter default privileges in schema ${schema}
  grant usage, select on sequences to service_role;
`;
}

for (const environment of environments) {
  const directory = `supabase/migrations/${environment}`;
  const schema = `zkblast_${environment}`;
  await mkdir(directory, { recursive: true });
  await writeFile(
    `${directory}/202610160001_identity_and_trade_history.sql`,
    migration(schema),
  );
}

console.log("Identity and trade-history migrations generated");
